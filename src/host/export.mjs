// `caw export <test>`: the recorded test as a Playwright test that runs without caw, only with @playwright/test. Writes
// <test>.spec.mjs (one test, one test.step per caw step), caw-support.mjs (sign-in, waiting, placeholders, dialogs; overwritten)
// and playwright.config.mjs (only if missing). The locators are the recorded ones, printed as Playwright code.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';

import { loadConfig, todoFields } from '../shared/config.mjs';
import { credentialNames } from '../shared/credentials.mjs';
import { chooseEnvironment, effectiveEnvironment, environmentCandidates, startPath } from '../shared/environments.mjs';
import { CawError, EXIT } from '../shared/errors.mjs';
import { t } from '../shared/i18n.mjs';
import { createUi } from '../shared/ui.mjs';
import { EXTJS_ENGINE } from './framework/extjs-engine.mjs';
import { frameworkOf } from './framework/index.mjs';
import { optionValue } from './linux.mjs';
import { parseLocator } from './locator.mjs';
import { recordedBrowser } from './replay.mjs';
import { templatePath } from './sandbox-config.mjs';
import { loadTest, staleSteps } from './test-file.mjs';

/** The first line of every file caw export writes; a file without it is someone else's and is never overwritten. */
export const GENERATED = '// GENERATED by caw export';
export const DEFAULT_OUT = 'caw/export/playwright';
const SUPPORT_FILE = 'caw-support.mjs';
const CONFIG_FILE_NAME = 'playwright.config.mjs';
/** Actions after which caw waits for the page to settle. */
const CHANGES_PAGE = new Set(['click', 'dblclick', 'press', 'goto', 'reload']);
const NOT_EXPORTED = 'Not exported: learned effects and network baselines, knownMessages, the console and request failure rules, '
    + 'retry, readyIgnore and the 2 s tolerance for a second match while a dialog closes.';

const js = (value) => JSON.stringify(value);
/** A text value: with a placeholder it is filled per run. */
const text = (value) => (String(value).includes('{{') ? `caw.text(${js(value)})` : js(value));

const isChain = (value) => value !== null && typeof value === 'object' && Array.isArray(value.chain);
const isRegExp = (value) => value instanceof RegExp;
/** A locator argument as JavaScript: strings and regular expressions with placeholders are filled per run. */
const exportValue = (value) => {
    if (typeof value === 'string') return text(value);
    if (isRegExp(value)) return value.source.includes('{{') ? `caw.regex(${js(value.source)}, ${js(value.flags)})` : String(value);
    if (isChain(value)) return exportChain(value.chain);
    if (value !== null && typeof value === 'object') return `{ ${Object.entries(value).map(([key, inner]) => `${key}: ${exportValue(inner)}`).join(', ')} }`;
    return String(value);
};
/** A parsed locator as Playwright code on `page`; nested locators (has, and, or) start at `page` too. */
const exportChain = (chain) => `page.${chain.map(({ method, args }) => `${method}(${args.map(exportValue).join(', ')})`).join('.')}`;
export const exportLocator = (code) => exportChain(parseLocator(code));

/** Does a locator use the extjs= engine (in locator() or frameLocator(), nested ones included)? */
const usesExtjs = (code) => /(?:locator|frameLocator)\(\s*'extjs=/.test(code);

/**
 * The lines of one recorded action. A dialog decision wraps the action; actions that may change the page are followed by
 * settling, as caw replays them.
 */
export const actionLines = (action) => {
    const target = action.target === undefined ? null : exportLocator(action.target);
    let call = null;
    switch (action.action) {
        case 'click': call = action.optional === true ? `caw.optional(${target})` : `${target}.click()`; break;
        case 'dblclick': call = `${target}.dblclick()`; break;
        case 'fill': call = `caw.fill(${target}, ${text(action.value)})`; break;
        case 'type': call = `${target}.pressSequentially(${text(action.value)})`; break;
        case 'upload': call = `caw.upload(${target}, ${js(action.files)})`; break;
        case 'download': call = `caw.download(${target}, new RegExp(${js(action.file)}))`; break;
        case 'hover': call = `${target}.hover()`; break;
        case 'dragTo': call = `${target}.dragTo(${exportLocator(action.to)})`; break;
        case 'press': call = `page.keyboard.press(${js(action.key)})`; break;
        // A refused navigation was recorded as proof of the host lock: Playwright has no such lock.
        case 'goto': if (action.denied === true) return [`// goto ${action.url} was refused by caw's host lock while recording; not exported.`]; call = `page.goto(${text(action.url)})`; break;
        case 'reload': call = 'page.reload()'; break;
        case 'wait-ready': {
            const options = { ...(action.for === undefined ? {} : { for: action.for }), ...(action.minCount === undefined ? {} : { minCount: action.minCount }) };
            call = `caw.waitReady(${Object.keys(options).length === 0 ? '' : js(options)})`;
            break;
        }
        case 'remember': call = `caw.remember(${js(action.name)}, ${js(action.code)})`; break;
        // Claude's evidence while recording, not part of the test.
        case 'screenshot': return [];
        default: return [`// ${action.action} is not exported.`];
    }
    const { dialog } = action;
    const lines = [dialog === undefined
        ? `await ${call};`
        : `await caw.dialog(${js({ accept: dialog.accept, ...(dialog.value === undefined ? {} : { value: dialog.value }) })}, () => ${call});`];
    if (CHANGES_PAGE.has(action.action)) lines.push('await caw.settle();');
    return lines;
};

/** The spec file of one test. */
export const specText = ({ spec, env, role, path }) => {
    const body = spec.steps.flatMap(({ id, name, recording }) => [
        `    await test.step(${js(`${id} ${name}`)}, async () => {`,
        ...recording.actions.flatMap(actionLines).map((line) => `        ${line}`),
        `        await caw.check(${js(recording.check)}${recording.timeoutMs === undefined ? '' : `, ${recording.timeoutMs}`});`,
        '    });',
    ]);
    return [
        `${GENERATED} from caw/tests/${spec.id}.yaml and caw/recordings/${spec.id}.yaml for environment ${env}. Export again after re-recording.`,
        `// ${NOT_EXPORTED}`,
        "import { test } from '@playwright/test';",
        '',
        `import { contextOptions, start } from './${SUPPORT_FILE}';`,
        '',
        `test.use(contextOptions(${js(role)}));`,
        '',
        `test(${js(spec.id)}, async ({ page }) => {`,
        `    const caw = await start(page, { role: ${js(role)}, path: ${js(path)} });`,
        ...body,
        '});',
        '',
    ].join('\n');
};

/** A path from the export folder to a file of the project, as a URL relative to the support module. */
const relativeUrl = (from, to) => {
    const path = relative(from, to).split(sep).join('/');
    return path.startsWith('.') ? path : `./${path}`;
};

/** caw-support.mjs: the template with this project's settings, the framework's readiness probe and, for ExtJS, the engine. */
export const supportText = ({ config, env, out, root, browser, extjs }) => {
    const framework = frameworkOf(config);
    const roles = Object.keys(config.roles ?? {});
    const settings = {
        env: env.name,
        url: env.url,
        framework: framework.name,
        signIn: env.signIn,
        gate: env.gate !== undefined,
        insecureTls: env.insecureTls,
        accounts: Object.fromEntries([...roles, 'gate'].map((who) => [who, credentialNames(who, env.name)])),
        sessions: Object.fromEntries(roles.map((role) => [role, relativeUrl(out, join(root, 'caw', '.auth', env.name, `${role}.json`))])),
        cawDir: relativeUrl(out, join(root, 'caw')),
        locale: browser.locale ?? null,
        timezone: browser.timezone ?? Intl.DateTimeFormat().resolvedOptions().timeZone,
        countNetwork: framework.countNetwork === true,
        ...(config.readyTimeoutMs === undefined ? {} : { readyTimeoutMs: config.readyTimeoutMs }),
    };
    const template = readFileSync(templatePath('export/caw-support.mjs.tpl'), 'utf8').replace(/\r\n/g, '\n');
    return template
        .replace('/* caw:settings */ {}', () => JSON.stringify(settings, null, 4))
        .replace('/* caw:probe */ null', () => String(framework.probe))
        .replace('/* caw:extjs */ null', () => (extjs ? js(EXTJS_ENGINE) : 'null'));
};

/** playwright.config.mjs: written once, then the team's. */
export const configText = ({ env, browser }) => [
    `${GENERATED}, once: change it as you like, export does not overwrite it.`,
    "import { defineConfig } from '@playwright/test';",
    '',
    'export default defineConfig({',
    "    testDir: '.',",
    "    testMatch: '*.spec.mjs',",
    '    timeout: 300_000,',
    "    reporter: [['list']],",
    '    use: {',
    `        baseURL: process.env.CAW_BASE_URL || ${js(env.url)},`,
    "        channel: 'chrome',",
    '        actionTimeout: 30_000,',
    "        trace: 'retain-on-failure',",
    ...(browser.locale === undefined ? [] : [`        locale: ${js(browser.locale)},`]),
    ...(browser.timezone === undefined ? [] : [`        timezoneId: ${js(browser.timezone)},`]),
    ...(browser.viewport === undefined ? [] : [`        viewport: ${js(browser.viewport)},`]),
    '    },',
    '});',
    '',
].join('\n');

/** Writes a generated file; one without the generated header belongs to someone else and stays. */
const writeGenerated = (file, content) => {
    if (existsSync(file) && !readFileSync(file, 'utf8').startsWith(GENERATED)) throw new CawError('usage', t('cli.export.foreignFile', { file }));
    writeFileSync(file, content);
};

/**
 * Exports one test.
 * @returns { files: written paths, kept: the config that already existed }
 */
export const exportTest = (root, id, { env: given, out = DEFAULT_OUT } = {}) => {
    const config = loadConfig(root);
    const spec = loadTest(root, id, { framework: config.framework ?? 'web' });
    const missing = spec.steps.filter(({ recording }) => recording === undefined).map(({ id: step }) => step);
    if (missing.length > 0) throw new CawError('replay-missing', t('cli.export.notRecorded', { test: id, steps: missing.join(', ') }));
    const stale = staleSteps(spec);
    if (stale.length > 0) throw new CawError('replay-stale', t('cli.export.stale', { test: id, steps: stale.map(({ id: step }) => step).join(', '), from: stale[0].id }));
    const { name } = chooseEnvironment(config, { given, candidates: environmentCandidates(config, { command: 'run', specs: [spec] }), command: 'export' });
    const env = effectiveEnvironment(config, name);
    const todo = todoFields(config);
    if (todo.length > 0) throw new CawError('config-invalid', t('cli.export.todo', { keys: todo.join(', ') }));
    const roles = Object.keys(config.roles ?? {});
    const role = env.signIn.type === 'none' && env.gate === undefined ? null : spec.role ?? (roles.length === 1 ? roles[0] : null);
    const browser = { ...recordedBrowser(spec.steps), ...Object.fromEntries(['locale', 'viewport'].filter((key) => config.browser?.[key] !== undefined).map((key) => [key, config.browser[key]])),
        ...(config.browser?.timezone === undefined ? {} : { timezone: config.browser.timezone }) };
    const extjs = config.framework === 'extjs' || spec.steps.some(({ recording }) => recording.actions.some((action) => [action.target, action.to].some((code) => typeof code === 'string' && usesExtjs(code))));
    const dir = resolve(root, out);
    mkdirSync(dir, { recursive: true });
    const specFile = join(dir, `${id}.spec.mjs`);
    const supportFile = join(dir, SUPPORT_FILE);
    const configFile = join(dir, CONFIG_FILE_NAME);
    writeGenerated(specFile, specText({ spec, env: name, role, path: startPath(config, spec) }));
    writeGenerated(supportFile, supportText({ config, env, out: dir, root, browser, extjs }));
    const kept = existsSync(configFile);
    if (!kept) writeFileSync(configFile, configText({ env, browser }));
    return { env: name, files: [specFile, supportFile, ...(kept ? [] : [configFile])], kept: kept ? configFile : null };
};

/** `caw export <test> [--env <name>] [--out <dir>]`. */
export const exportCommand = async (root, args, { ui = createUi() } = {}) => {
    const valued = ['--env', '--out'];
    const words = args.filter((arg, index) => !valued.some((flag) => arg === flag || arg.startsWith(`${flag}=`)) && !valued.includes(args[index - 1]));
    const unknown = words.find((word) => word.startsWith('-'));
    if (unknown !== undefined) throw new CawError('usage', t('cli.export.unknownArg', { arg: unknown }));
    if (words.length !== 1) throw new CawError('usage', t('cli.export.usage'));
    const { env, files, kept } = exportTest(root, words[0], { env: optionValue(args, '--env'), out: optionValue(args, '--out') ?? DEFAULT_OUT });
    // Inside the project relative to it, outside as the full path.
    const shown = (file) => {
        const path = relative(root, file);
        return path.startsWith('..') ? file : path.split(sep).join('/');
    };
    ui.success(t('cli.export.done', { test: words[0], env, files: files.map(shown).join(', ') }));
    if (kept !== null) ui.note(t('cli.export.configKept', { file: shown(kept) }));
    ui.note(t('cli.export.next', { dir: shown(resolve(files[0], '..')) }));
    return EXIT.pass;
};
